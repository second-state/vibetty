//! `vibetty setup` —— 配置 MQTT 传输,写入 `~/.vibetty/config.toml` 的 `[mqtt]` 段。
//!
//! dialoguer 交互流:依次询问 broker URL 和 keep-alive 秒数,最后确认是否保存。
//! config 文件不存在时会先生成一份开箱即用的骨架(localhost 内置 broker)。

use anyhow::Context;
use dialoguer::console::style;
use dialoguer::theme::ColorfulTheme;
use dialoguer::{Confirm, Input};

use crate::config::MqttConfig;

fn config_path(override_path: Option<&std::path::Path>) -> Option<std::path::PathBuf> {
    match override_path {
        Some(p) => Some(p.to_path_buf()),
        None => dirs::home_dir().map(|h| h.join(".vibetty").join("config.toml")),
    }
}

/// 读取现有 `[mqtt]` 段,用于预填表单。config 文件不存在时先生成一份带注释骨架
/// (含 `[mqtt]` 段),让首次运行的用户有东西可看可改,再从生成的文件里读回默认值。
fn load_mqtt(override_path: Option<&std::path::Path>) -> Option<MqttConfig> {
    let path = config_path(override_path)?;
    if !path.exists() {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).ok();
        }
        // 已存在就不动(下面的 read_to_string 会正常读);只在缺文件时落一份骨架。
        std::fs::write(&path, default_config_toml()).ok();
        log::info!(
            "[setup] no config file at {}; generated a starter one",
            path.display()
        );
    }
    let content = std::fs::read_to_string(&path).ok()?;
    #[derive(serde::Deserialize)]
    struct Section {
        #[serde(default)]
        mqtt: Option<MqttConfig>,
    }
    toml::from_str::<Section>(&content).ok()?.mqtt
}

/// 新用户的初始 config.toml 骨架:`[mqtt]` 表单字段 + 注释说明(broker 指向 localhost
/// 即自动用内置 broker)。builtin_ws_port 也写出(0 = 不开 WS),但不在交互里询问。
fn default_config_toml() -> String {
    r#"# vibetty configuration (generated by `vibetty setup`)
# Edit with `vibetty setup`, or by hand.

[mqtt]
# Broker URL. If the host is localhost / 127.0.0.1, vibetty automatically starts
# its built-in broker on the port in this URL (default 1883) — nothing else to run.
broker = "mqtt://127.0.0.1:1883"
keep_alive_secs = 30
# Built-in broker WebSocket port; 0 = disable (default). Only the /mqtt_ws debug
# page uses it.
builtin_ws_port = 0
"#
    .to_string()
}

/// 把 `[mqtt]` 段写回 config.toml(默认 `~/.vibetty/config.toml`),保留文件中已有的其它段。
pub(crate) fn save_mqtt(
    mqtt: &MqttConfig,
    override_path: Option<&std::path::Path>,
) -> anyhow::Result<()> {
    let path =
        config_path(override_path).ok_or_else(|| anyhow::anyhow!("Cannot find home directory"))?;
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let mut table: toml::Table = std::fs::read_to_string(&path)
        .ok()
        .and_then(|s| toml::from_str(&s).ok())
        .unwrap_or_default();
    table.insert("mqtt".to_string(), toml::Value::try_from(mqtt)?);
    std::fs::write(&path, toml::to_string_pretty(&table)?)?;
    Ok(())
}

pub fn run_setup(config: Option<std::path::PathBuf>) -> anyhow::Result<()> {
    let override_path = config.as_deref();
    let path = config_path(override_path)
        .ok_or_else(|| anyhow::anyhow!("Cannot find home directory"))?
        .display()
        .to_string();
    let existing = load_mqtt(override_path);
    // builtin_ws_port 不在交互里询问:透传已有配置里的值,不丢用户之前的设置。
    let builtin_ws_port = existing
        .as_ref()
        .map(|c| c.builtin_ws_port)
        .unwrap_or_default();

    println!(
        "{}",
        style(format!("vibetty setup ({path})")).bold().underlined()
    );
    println!(
        "{}",
        style(
            "tip: a localhost / 127.0.0.1 broker URL makes vibetty auto-start its built-in broker"
        )
        .dim()
    );
    println!();

    let theme = &ColorfulTheme::default();

    let broker: String = Input::with_theme(theme)
        .with_prompt("Broker URL")
        .with_initial_text(
            existing
                .as_ref()
                .map(|c| c.broker.clone())
                .unwrap_or_else(|| "mqtt://127.0.0.1:1883".into()),
        )
        .interact_text()?;

    let keep_alive_secs: u64 = Input::with_theme(theme)
        .with_prompt("Keep-alive seconds")
        .default(30)
        .interact_text()?;

    let cfg = MqttConfig {
        broker,
        keep_alive_secs,
        builtin_ws_port,
    };

    let save = Confirm::with_theme(theme)
        .with_prompt(format!("Save to {path}?"))
        .default(true)
        .interact()?;

    if save {
        save_mqtt(&cfg, override_path).with_context(|| format!("saving {path}"))?;
        println!("{}", style("✔ Saved.").green().bold());
    } else {
        println!("{}", style("Discarded — nothing written.").yellow());
    }

    Ok(())
}

/// 把 `[ui] border` 写回 config.toml(菜单里切换边框时持久化)。
/// 与 `save_mqtt` 同思路:读整份 toml::Table,只合并 `ui.border` 一个键,
/// 保留 `menu_key` 和其它段不动。
pub(crate) fn save_ui_border(
    border: bool,
    override_path: Option<&std::path::Path>,
) -> anyhow::Result<()> {
    let path =
        config_path(override_path).ok_or_else(|| anyhow::anyhow!("Cannot find home directory"))?;
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let mut table: toml::Table = std::fs::read_to_string(&path)
        .ok()
        .and_then(|s| toml::from_str(&s).ok())
        .unwrap_or_default();
    let ui = table
        .entry("ui")
        .or_insert_with(|| toml::Value::Table(toml::Table::new()));
    if let Some(ui_table) = ui.as_table_mut() {
        ui_table.insert("border".to_string(), toml::Value::Boolean(border));
    }
    std::fs::write(&path, toml::to_string_pretty(&table)?)?;
    Ok(())
}
